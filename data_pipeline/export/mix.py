# ---------------- what the model sees ----------------
def navila_prompt(q: str, n_frames: int = NUM_FRAMES) -> str:
    """The question LazyVLNCEDataset builds around a record's instruction (llava/data/dataset.py)."""
    instruction = q.replace("\r\n", " ").replace("\n", " ")
    instruction = re.sub(r"(?<=\.\s)([a-z])", lambda x: x.group().upper(), instruction.capitalize())
    instruction = re.sub(r"\s+\.", ".", instruction)
    image_tokens = "<image>\n" * (n_frames - 1)
    return (f"Imagine you are a robot programmed for navigation tasks. You have been given a video "
            f'of historical observations {image_tokens}, and current observation <image>\n. Your assigned task is: "{instruction}" '
            f"Analyze this series of images to decide your next action, which could be turning left or right by a specific "
            f"degree, moving forward a certain distance, or stop if the task is completed.")


def sample_history(frames: list, num: int = NUM_FRAMES) -> list:
    """llava/mm_utils.py vlnce_frame_sampling: black frames (None here) in front up to num, then num - 1
    spread over the history from its start, plus the current (last) frame."""
    frames = [None] * (num - len(frames)) + list(frames)
    idx = np.linspace(0, len(frames) - 1, num=num - 1, endpoint=False, dtype=int)
    return [frames[i] for i in idx] + [frames[-1]]


def contact_sheet(paths: list, size: int = 160) -> bytes:
    """PNG of the frames side by side; None or a missing file is black."""
    import cv2

    tiles = []
    for p in paths:
        img = cv2.imread(str(p)) if p is not None and Path(p).exists() else None
        tiles.append(cv2.resize(img, (size, size)) if img is not None else np.zeros((size, size, 3), np.uint8))
    return cv2.imencode(".png", np.hstack(tiles))[1].tobytes()


# ---------------- checks ----------------
def check_dataset(data_path: Path, image_dir: Path, check_frames: bool = True) -> dict:
    """What NaVILA's loader needs: keys, a known answer, a parseable video_id, every frame on disk."""
    with open(data_path) as f:
        recs = json.load(f)
    problems, answers, missing, frames = Counter(), Counter(), set(), set()
    for r in recs:
        if set(r) != {"video_id", "q", "a", "frames"}:
            problems["keys"] += 1
            continue
        try:
            split_video_id(r["video_id"])
        except ValueError:
            problems["video_id"] += 1
        action = parse_answer(r["a"])
        if action is None:
            problems["unknown answer"] += 1
        else:
            answers[action.kind] += 1
        if not r["q"].strip():
            problems["empty instruction"] += 1
        if not r["frames"]:
            problems["no frames"] += 1
        frames.update(r["frames"])
    if check_frames:
        missing = {p for p in frames if not (Path(image_dir) / p).exists()}
    n = max(len(recs), 1)
    return {"records": len(recs), "frames": len(frames), "missing frames": len(missing),
            "problems": dict(problems), "record share": {k: round(v / n, 3) for k, v in answers.most_common()},
            "missing (first 3)": sorted(missing)[:3]}
