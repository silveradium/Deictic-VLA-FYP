"""Mix our episodes with NaVILA replay data: ratio, registration in NaVILA, training flags, checks.

NaVILA mixes datasets by name: `--data_mixture deictic*4+r2r_replay+rxr_replay` concatenates them,
`*N` repeating one N times per epoch (llava/data/builder.py). Each name is registered in
llava/data/datasets_mixture.py as a Dataset with dataset_type "vlnce" (LazyVLNCEDataset).

navila_prompt and sample_history reproduce what LazyVLNCEDataset does with a record, to look at
samples exactly as the model will see them.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from pathlib import Path

import numpy as np

from data_pipeline.export.navila_data import parse_answer, split_video_id

NUM_FRAMES = 8  # --num_video_frames of navila-llama3-8b-8f


def deictic_repeat(n_deictic: int, n_replay: int, replay_per_deictic: float) -> int:
    """*N for our set so that replay records / our records ~ replay_per_deictic (at least 1)."""
    if n_deictic == 0:
        return 1
    return max(1, round(n_replay / (replay_per_deictic * n_deictic)))


def mixture(parts: dict[str, int]) -> str:
    return "+".join(name if times == 1 else f"{name}*{times}" for name, times in parts.items())


def registration(datasets: dict[str, tuple[str, str]]) -> str:
    """Python to paste into register_datasets_mixtures() in NaVILA's llava/data/datasets_mixture.py.
    datasets: name -> (data_path, image_path) as seen on the training machine."""
    out = ["    # deictic fine-tuning + NaVILA replay (generated by data_pipeline/export/mix_navila.ipynb)"]
    for name, (data_path, image_path) in datasets.items():
        assert name == name.lower() and "+" not in name and "*" not in name, name  # --data_mixture is lowercased
        out += [f"    {name} = Dataset(",
                f'        dataset_name="{name}",',
                '        dataset_type="vlnce",',
                f'        data_path="{data_path}",',
                f'        image_path="{image_path}",',
                "    )",
                f"    add_dataset({name})",
                ""]
    return "\n".join(out)


